    __device__ inline int label_bar_width(const GpuDrawBox& box) {
        int n = 0;
        while (n < 31 && box.label[n] != '\0') ++n;
        return n * 8;
    }

    __device__ __forceinline__ void set_pixel(uint8_t* __restrict__ bgr, int width,
                                              int x, int y, const GpuDrawBox& box) {
        uint8_t* p = bgr + (static_cast<size_t>(y) * width + x) * 3;
        p[0] = box.b;
        p[1] = box.g;
        p[2] = box.r;
    }

