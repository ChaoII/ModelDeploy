        const int b = blockIdx.x;
        if (b >= num_boxes) return;
        const GpuDrawBox box = boxes[b];
        const int tid = threadIdx.x;

        const int x1 = max(box.x1, 0);
        const int y1 = max(box.y1, 0);
        const int x2 = min(box.x2, width);
        const int y2 = min(box.y2, height);
        if (x1 >= x2 || y1 >= y2) return;

        const int bar_w = label_bar_width(box);
        const int lx1 = x1 + 2;              // 标签条左边界（避开 2px 左边框）
        const int lx2 = lx1 + bar_w;         // 标签条右边界（不含）
        const int ly1 = y1;                  // 标签条上边界（压过顶边框）
        const int ly2 = y1 + 16;             // 标签条下边界（不含）

        const float one_minus = 1.0f - alpha;

        // ── 填充内部（半透明）──
        if (tid < 128) {
            const int ix1 = x1 + 2;
            const int iy1 = y1 + 2;
            const int ix2 = max(x2 - 2, ix1);
            const int iy2 = max(y2 - 2, iy1);
            for (int y = iy1 + tid / 16; y < iy2; y += 8) {
                const bool in_label_y = (y >= ly1 && y < ly2);
                for (int x = ix1 + (tid % 16); x < ix2; x += 16) {
                    if (in_label_y && x >= lx1 && x < lx2) continue;
                    uint8_t* p = bgr + (static_cast<size_t>(y) * width + x) * 3;
                    p[0] = static_cast<uint8_t>(p[0] * one_minus + box.b * alpha + 0.5f);
                    p[1] = static_cast<uint8_t>(p[1] * one_minus + box.g * alpha + 0.5f);
                    p[2] = static_cast<uint8_t>(p[2] * one_minus + box.r * alpha + 0.5f);
                }
            }
            return;
        }

        // ── 2px 边框（四个角归水平边；竖直边只画内部行，避免重叠写入）──
        const int t = tid - 128;   // 0..127
        if (t < 64) {
            const int side = t / 32;     // 0 顶，1 底
            const int xbase = t % 32;
            if (side == 0) {
                for (int r = 0; r < 2; ++r) {
                    const int y = y1 + r;
                    for (int x = x1 + xbase; x < x2; x += 32) {
                        if (x >= lx1 && x < lx2) continue;   // 顶边框跳过标签条
                        set_pixel(bgr, width, x, y, box);
                    }
                }
            } else {
                for (int r = 0; r < 2; ++r) {
                    const int y = y2 - 2 + r;
                    if (y >= y1 && y < y2) {
                        for (int x = x1 + xbase; x < x2; x += 32) {
                            set_pixel(bgr, width, x, y, box);
                        }
                    }
                }
            }
        } else {
            const int tt = t - 64;       // 0..63
            const int side = tt / 32;    // 0 左，1 右
            const int ybase = tt % 32;
            const int x0 = (side == 0) ? x1 : (x2 - 2);
            for (int r = 0; r < 2; ++r) {
                const int x = x0 + r;
                if (x < x1 || x >= x2) continue;
                for (int y = y1 + 2 + ybase; y < y2 - 2; y += 32) {
                    set_pixel(bgr, width, x, y, box);
                }
            }
        }

        // ── 顶部标签条：白字 + 实底色（独占区域：填充与顶边框均已跳过）──
        if (bar_w > 0 && lx2 <= x2) {
            for (int x = lx1 + t; x < lx2; x += 128) {
                if (x < 0 || x >= width) continue;
                const int ci = (x - lx1) / 8;
                const int bc = (x - lx1) % 8;
                const char ch = box.label[ci];
                if (ch < 0x20 || ch > 0x7E) continue;
                for (int r = 0; r < 16; ++r) {
                    const int y = ly1 + r;
                    if (y < 0 || y >= height) continue;
                    const uint8_t bits = FONT8X16[ch - 0x20][r];
                    uint8_t* p = bgr + (static_cast<size_t>(y) * width + x) * 3;
                    if (bits & (0x80 >> bc)) {
                        p[0] = 255; p[1] = 255; p[2] = 255;
                    } else {
                        p[0] = box.b; p[1] = box.g; p[2] = box.r;
                    }
                }
            }
        }
    }

    struct DrawGpuWorkspace {
        uint8_t* d_bgr = nullptr;
        GpuDrawBox* d_boxes = nullptr;
        size_t bgr_capacity = 0;
        size_t boxes_capacity = 0;

        ~DrawGpuWorkspace() {
            if (d_bgr) cudaFree(d_bgr);
            if (d_boxes) cudaFree(d_boxes);
        }
    };

    static thread_local DrawGpuWorkspace draw_gpu_ws;

    bool draw_boxes_gpu(uint8_t* bgr, int width, int height,
                        const GpuDrawBox* d_boxes, int num_boxes,
                        float alpha, cudaStream_t stream) {
        if (!bgr || width <= 0 || height <= 0 || !d_boxes || num_boxes <= 0) return true;

        bool is_internal_stream = false;
        if (stream == nullptr) {
            if (cudaStreamCreate(&stream) != cudaSuccess) return false;
            is_internal_stream = true;
        }

        const size_t bgr_bytes = static_cast<size_t>(height) * width * 3;
        const size_t boxes_bytes = sizeof(GpuDrawBox) * static_cast<size_t>(num_boxes);

        // d_boxes 指针可能是 host（调用方直接传 std::vector.data()）→ 自动上传
        cudaPointerAttributes box_attr{};
        const bool boxes_on_device =
            cudaPointerGetAttributes(&box_attr, d_boxes) == cudaSuccess &&
            box_attr.type == cudaMemoryTypeDevice;
        const GpuDrawBox* d_boxes_ptr;
        if (boxes_on_device) {
            d_boxes_ptr = d_boxes;
        } else {
            if (draw_gpu_ws.boxes_capacity < boxes_bytes) {
                GpuDrawBox* new_buf = nullptr;
                if (cudaMalloc(&new_buf, boxes_bytes) != cudaSuccess) {
                    // 分配失败：旧缓冲区仍有效，保持原状态，交由调用方回退 CPU 绘制
                    if (is_internal_stream) cudaStreamDestroy(stream);
                    return false;
                }
                if (draw_gpu_ws.d_boxes) cudaFree(draw_gpu_ws.d_boxes);
                draw_gpu_ws.d_boxes = new_buf;
                draw_gpu_ws.boxes_capacity = boxes_bytes;
            }
            cudaError_t upload_err =
                cudaMemcpyAsync(draw_gpu_ws.d_boxes, d_boxes, boxes_bytes, cudaMemcpyHostToDevice, stream);
            if (upload_err != cudaSuccess) {
                if (is_internal_stream) cudaStreamDestroy(stream);
                return false;
            }
            d_boxes_ptr = draw_gpu_ws.d_boxes;
        }

        // bgr 指针 device/host 检测（host 则上传，绘制后回拷，保证调用方看到结果）
        cudaPointerAttributes bgr_attr{};
        const bool bgr_on_device =
            cudaPointerGetAttributes(&bgr_attr, bgr) == cudaSuccess &&
            bgr_attr.type == cudaMemoryTypeDevice;

        uint8_t* d_bgr_ptr;
        if (bgr_on_device) {
            d_bgr_ptr = bgr;
        } else {
            if (draw_gpu_ws.bgr_capacity < bgr_bytes) {
                uint8_t* new_buf = nullptr;
                if (cudaMalloc(&new_buf, bgr_bytes) != cudaSuccess) {
                    if (is_internal_stream) cudaStreamDestroy(stream);
                    return false;
                }
                if (draw_gpu_ws.d_bgr) cudaFree(draw_gpu_ws.d_bgr);
                draw_gpu_ws.d_bgr = new_buf;
                draw_gpu_ws.bgr_capacity = bgr_bytes;
            }
            cudaError_t upload_err =
                cudaMemcpyAsync(draw_gpu_ws.d_bgr, bgr, bgr_bytes, cudaMemcpyHostToDevice, stream);
            if (upload_err != cudaSuccess) {
                if (is_internal_stream) cudaStreamDestroy(stream);
                return false;
            }
            d_bgr_ptr = draw_gpu_ws.d_bgr;
        }

        dim3 grid(static_cast<unsigned>(num_boxes));
        dim3 block(256);
        kernel_draw_boxes<<<grid, block, 0, stream>>>(
            d_bgr_ptr, width, height, d_boxes_ptr, num_boxes, alpha);

        cudaError_t launch_err = cudaGetLastError();
        cudaError_t copy_err = cudaSuccess;
        if (!bgr_on_device) {
            copy_err = cudaMemcpyAsync(bgr, d_bgr_ptr, bgr_bytes, cudaMemcpyDeviceToHost, stream);
        }
        cudaError_t sync_err = cudaStreamSynchronize(stream);
        if (is_internal_stream) cudaStreamDestroy(stream);
        return launch_err == cudaSuccess && copy_err == cudaSuccess && sync_err == cudaSuccess;
    }
